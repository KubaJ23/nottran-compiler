    @Override
    public TacParam visitCharLiteral(Literal.CharLiteral l) {
        // --- String Literal Implementation ---
        // Returns a pointer (in a temp) to a new heap-allocated string object.

        String s = l.value();
        int len = s.length();
        int totalSizeInWords = 1 + len; // 1 word for length + N words for chars

        TacParam.Variable t_size = newTemp();
        add(TacOp.LOAD_CONST, t_size, new TacParam.Value(totalSizeInWords), null);

        TacParam.Variable t_ptr = newTemp(); // This ptr is the result
        add(TacOp.ALLOCATE, t_ptr, t_size, null);

        // Store the length at ptr[0]
        TacParam.Variable t_len = newTemp();
        add(TacOp.LOAD_CONST, t_len, new TacParam.Value(len), null);

        TacParam.Variable t_zero = newTemp();
        add(TacOp.LOAD_CONST, t_zero, new TacParam.Value(0), null);

        add(TacOp.INDEX_WRITE, t_ptr, t_zero, t_len); // t_ptr[0] = len

        // Store each character
        TacParam.Variable t_one = newTemp();
        add(TacOp.LOAD_CONST, t_one, new TacParam.Value(1), null);

        TacParam.Variable t_idx = newTemp();
        add(TacOp.LOAD_CONST, t_idx, new TacParam.Value(1), null); // i = 1

        for (int i = 0; i < len; i++) {
            TacParam.Variable t_char = newTemp();
            int asciiVal = (int) s.charAt(i);
            add(TacOp.LOAD_CONST, t_char, new TacParam.Value(asciiVal), null); // char

            add(TacOp.INDEX_WRITE, t_ptr, t_idx, t_char); // t_ptr[i] = char

            if (i < len - 1) { // Don't increment on last iteration
                add(TacOp.ADD, t_idx, t_idx, t_one); // i = i + 1
            }
        }
        return t_ptr;
    }

    // --- String Helper Methods ---

    /**
     * Generates TAC for: result_ptr = s1_ptr // s2_ptr
     * Returns a temp (t_new_ptr) holding the pointer to the new string.
     */
    private TacParam generateStringConcat(TacParam s1_ptr, TacParam s2_ptr) {
        TacParam.Variable t_zero = newTemp();
        add(TacOp.LOAD_CONST, t_zero, new TacParam.Value(0), null);
        TacParam.Variable t_one = newTemp();
        add(TacOp.LOAD_CONST, t_one, new TacParam.Value(1), null);

        // 1. Get len1 = s1_ptr[0]
        TacParam.Variable t_len1 = newTemp();
        add(TacOp.INDEX_READ, t_len1, s1_ptr, t_zero);

        // 2. Get len2 = s2_ptr[0]
        TacParam.Variable t_len2 = newTemp();
        add(TacOp.INDEX_READ, t_len2, s2_ptr, t_zero);

        // 3. newLen = len1 + len2
        TacParam.Variable t_new_len = newTemp();
        add(TacOp.ADD, t_new_len, t_len1, t_len2);

        // 4. totalSize = 1 + newLen
        TacParam.Variable t_total_size = newTemp();
        add(TacOp.ADD, t_total_size, t_one, t_new_len);

        // 5. Allocate memory for new string
        TacParam.Variable t_new_ptr = newTemp(); // This is our result
        add(TacOp.ALLOCATE, t_new_ptr, t_total_size, null);

        // 6. Store newLen at new_ptr[0]
        add(TacOp.INDEX_WRITE, t_new_ptr, t_zero, t_new_len);

        // --- Loop 1: Copy s1 into new_ptr ---
        TacParam.Variable t_i = newTemp();
        add(TacOp.LOAD_CONST, t_i, new TacParam.Value(1), null); // i = 1
        TacParam.Label loop1_start = newLabel("concat_loop1_start");
        TacParam.Label loop1_end = newLabel("concat_loop1_end");

        add(TacOp.LABEL, loop1_start, null, null);
        TacParam.Variable t_cond1 = newTemp();
        add(TacOp.GRT, t_cond1, t_i, t_len1);
        add(TacOp.GOTO_IF_TRUE, loop1_end, t_cond1, null); // if (i > len1) end

        TacParam.Variable t_char1 = newTemp();
        add(TacOp.INDEX_READ, t_char1, s1_ptr, t_i);       // t_char1 = s1[i]
        add(TacOp.INDEX_WRITE, t_new_ptr, t_i, t_char1);     // new_ptr[i] = t_char1
        add(TacOp.ADD, t_i, t_i, t_one);                // i = i + 1
        add(TacOp.GOTO, loop1_start, null, null);
        add(TacOp.LABEL, loop1_end, null, null);

        // --- Loop 2: Copy s2 into new_ptr ---
        TacParam.Variable t_j = newTemp();
        add(TacOp.LOAD_CONST, t_j, new TacParam.Value(1), null); // j = 1
        TacParam.Label loop2_start = newLabel("concat_loop2_start");
        TacParam.Label loop2_end = newLabel("concat_loop2_end");

        add(TacOp.LABEL, loop2_start, null, null);
        TacParam.Variable t_cond2 = newTemp();
        add(TacOp.GRT, t_cond2, t_j, t_len2);
        add(TacOp.GOTO_IF_TRUE, loop2_end, t_cond2, null); // if (j > len2) end

        // idx = len1 + j
        TacParam.Variable t_new_idx = newTemp();
        add(TacOp.ADD, t_new_idx, t_len1, t_j);

        TacParam.Variable t_char2 = newTemp();
        add(TacOp.INDEX_READ, t_char2, s2_ptr, t_j);       // t_char2 = s2[j]
        add(TacOp.INDEX_WRITE, t_new_ptr, t_new_idx, t_char2); // new_ptr[idx] = t_char2
        add(TacOp.ADD, t_j, t_j, t_one);                // j = j + 1
        add(TacOp.GOTO, loop2_start, null, null);
        add(TacOp.LABEL, loop2_end, null, null);

        // 9. Return the pointer to the new string
        return t_new_ptr;
    }

    /**
     * Generates TAC for: result = s1_ptr == s2_ptr
     * Returns a temp (t_result) holding 1 for true, 0 for false.
     */
    private TacParam generateStringEquals(TacParam s1_ptr, TacParam s2_ptr) {
        TacParam.Variable t_result = newTemp(); // Our final result
        TacParam.Variable t_zero = newTemp();
        add(TacOp.LOAD_CONST, t_zero, new TacParam.Value(0), null);
        TacParam.Variable t_one = newTemp();
        add(TacOp.LOAD_CONST, t_one, new TacParam.Value(1), null);

        TacParam.Label loopStart = newLabel("streq_loop");
        TacParam.Label notEqual = newLabel("streq_noteql");
        TacParam.Label isEqual = newLabel("streq_eql");
        TacParam.Label end = newLabel("streq_end");

        // 1. Get length of s1
        TacParam.Variable t_len1 = newTemp();
        add(TacOp.INDEX_READ, t_len1, s1_ptr, t_zero); // t_len1 = s1[0]

        // 2. Get length of s2
        TacParam.Variable t_len2 = newTemp();
        add(TacOp.INDEX_READ, t_len2, s2_ptr, t_zero); // t_len2 = s2[0]

        // 3. Check if lengths are different
        TacParam.Variable t_len_cond = newTemp();
        add(TacOp.NEQ, t_len_cond, t_len1, t_len2);
        add(TacOp.GOTO_IF_TRUE, notEqual, t_len_cond, null); // If (len1 != len2), goto notEqual

        // 4. Loop component: char-by-char comparison
        TacParam.Variable t_i = newTemp();
        add(TacOp.LOAD_CONST, t_i, new TacParam.Value(1), null); // i = 1 (char data starts at 1)

        add(TacOp.LABEL, loopStart, null, null);
        // 5. Check loop condition (i > len1)
        TacParam.Variable t_loop_cond = newTemp();
        add(TacOp.GRT, t_loop_cond, t_i, t_len1);
        add(TacOp.GOTO_IF_TRUE, isEqual, t_loop_cond, null); // If (i > len1), we are done, goto isEqual

        // 6. Get s1[i]
        TacParam.Variable t_char1 = newTemp();
        add(TacOp.INDEX_READ, t_char1, s1_ptr, t_i);

        // 7. Get s2[i]
        TacParam.Variable t_char2 = newTemp();
        add(TacOp.INDEX_READ, t_char2, s2_ptr, t_i);

        // 8. Compare characters
        TacParam.Variable t_char_cond = newTemp();
        add(TacOp.NEQ, t_char_cond, t_char1, t_char2);
        add(TacOp.GOTO_IF_TRUE, notEqual, t_char_cond, null); // If (char1 != char2), goto notEqual

        // 9. Increment i
        add(TacOp.ADD, t_i, t_i, t_one);
        add(TacOp.GOTO, loopStart, null, null);

        // 10. Labels
        add(TacOp.LABEL, notEqual, null, null);
        add(TacOp.ASSIGN, t_result, t_zero, null); // result = 0 (false)
        add(TacOp.GOTO, end, null, null);

        add(TacOp.LABEL, isEqual, null, null);
        add(TacOp.ASSIGN, t_result, t_one, null); // result = 1 (true)

        add(TacOp.LABEL, end, null, null);
        return t_result;
    }

