package uk.ac.nott.cs.comp3012.coursework.ast;

import org.antlr.v4.runtime.Token;
import org.antlr.v4.runtime.tree.ParseTree;
import org.antlr.v4.runtime.tree.TerminalNode;
import uk.ac.nott.cs.comp3012.coursework.NottscriptBaseVisitor;
import uk.ac.nott.cs.comp3012.coursework.NottscriptParser;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.stream.Collectors;

// Import all the AST node definitions
import uk.ac.nott.cs.comp3012.coursework.ast.Ast.*;
import uk.ac.nott.cs.comp3012.coursework.ast.Ast.ProgramUnit.*;
import uk.ac.nott.cs.comp3012.coursework.ast.Ast.Statement.*;
import uk.ac.nott.cs.comp3012.coursework.ast.Ast.TypeSpec.*;
import uk.ac.nott.cs.comp3012.coursework.ast.Ast.Dimension.*;
import uk.ac.nott.cs.comp3012.coursework.ast.Ast.Expression.*;
import uk.ac.nott.cs.comp3012.coursework.ast.Ast.Expression.Literal.*;
import uk.ac.nott.cs.comp3012.coursework.ast.Ast.TypeSpec.IntrinsicType.VarType;

/**
 * Builds the abstract syntax tree (AST) from the parse tree generated by ANTLR.
 * This visitor maps ANTLR's ParseTree contexts to the corresponding Ast node records.
 */
public class AstBuilder extends NottscriptBaseVisitor<Ast> {

    // -----------------------------------------------------------------
    // Top-Level Rules
    // -----------------------------------------------------------------

    @Override
    public Ast visitCompilationUnit(NottscriptParser.CompilationUnitContext ctx) {
        ProgramUnit.ProgramDecl program = (ProgramUnit.ProgramDecl) visit(ctx.programDeclaration());
        List<ProgramUnit> units = new ArrayList<>();
        for (NottscriptParser.ProgramUnitContext unitCtx : ctx.programUnit()) {
            units.add((ProgramUnit) visit(unitCtx));
        }
        return new CompilationUnit(ctx.start, program, units);
    }

    @Override
    public Ast visitProgramDeclaration(NottscriptParser.ProgramDeclarationContext ctx) {
        String name = ctx.NAME(0).getText();
        List<VariableDecl> decls = (ctx.declarationBlock() != null) ? visitAndMap(ctx.declarationBlock().variableDecl(), VariableDecl.class) : Collections.emptyList();
        List<Statement> stmts = visitAndMap(ctx.statementBlock().statement(), Statement.class);
        return new ProgramDecl(ctx.start, name, decls, stmts);
    }

    @Override
    public Ast visitFunctionDeclaration(NottscriptParser.FunctionDeclarationContext ctx) {
        String name = ctx.NAME(0).getText();
        List<String> params = visitANameList(ctx.nameList());

        // The result name is the NAME token *after* the RESULT token, if it exists
        String resultName = (ctx.RESULT() != null) ? ctx.NAME(1).getText() : null;

        List<VariableDecl> decls = (ctx.declarationBlock() != null) ? visitAndMap(ctx.declarationBlock().variableDecl(), VariableDecl.class) : Collections.emptyList();
        List<Statement> stmts = visitAndMap(ctx.statementBlock().statement(), Statement.class);

        return new FunctionDecl(ctx.start, name, params, resultName, decls, stmts);
    }

    @Override
    public Ast visitSubroutineDeclaration(NottscriptParser.SubroutineDeclarationContext ctx) {
        String name = ctx.NAME(0).getText();
        List<String> params = visitANameList(ctx.nameList());
        List<VariableDecl> decls = (ctx.declarationBlock() != null) ? visitAndMap(ctx.declarationBlock().variableDecl(), VariableDecl.class) : Collections.emptyList();
        List<Statement> stmts = visitAndMap(ctx.statementBlock().statement(), Statement.class);
        return new SubroutineDecl(ctx.start, name, params, decls, stmts);
    }

    @Override
    public Ast visitDerivedTypeDeclaration(NottscriptParser.DerivedTypeDeclarationContext ctx) {
        String name = ctx.NAME(0).getText();
        List<VariableDecl> fields = (ctx.derivedTypeDeclBlock() != null) ? visitAndMap(ctx.derivedTypeDeclBlock().derivedTypeVarDecl(), VariableDecl.class) : Collections.emptyList();
        return new DerivedTypeDecl(ctx.start, name, fields);
    }

    // -----------------------------------------------------------------
    // Declarations
    // -----------------------------------------------------------------

    @Override
    public Ast visitVariableDecl(NottscriptParser.VariableDeclContext ctx) {
        TypeSpec type = (TypeSpec) visit(ctx.typeSpec());
        boolean isPointer = (ctx.POINTER() != null);
        List<String> names = visitANameList(ctx.nameList());
        return new VariableDecl(ctx.start, type, isPointer, names);
    }

    @Override
    public Ast visitDerivedTypeVarDecl(NottscriptParser.DerivedTypeVarDeclContext ctx) {
        TypeSpec type = (TypeSpec) visit(ctx.typeSpec());
        List<String> names = visitANameList(ctx.nameList());
        // Fields in a derived type cannot be pointers according to this grammar
        return new VariableDecl(ctx.start, type, false, names);
    }

    // --- Type Specifications ---

    @Override
    public Ast visitIntegerType(NottscriptParser.IntegerTypeContext ctx) {
        List<Dimension> dims = visitAnArraySpec(ctx.arraySpec());
        return new IntrinsicType(ctx.start, VarType.INTEGER, dims);
    }

    @Override
    public Ast visitRealType(NottscriptParser.RealTypeContext ctx) {
        List<Dimension> dims = visitAnArraySpec(ctx.arraySpec());
        return new IntrinsicType(ctx.start, VarType.REAL, dims);
    }

    @Override
    public Ast visitCharType(NottscriptParser.CharTypeContext ctx) {
        List<Dimension> dims = visitAnArraySpec(ctx.arraySpec());
        return new IntrinsicType(ctx.start, VarType.CHARACTER, dims);
    }

    @Override
    public Ast visitLogicalType(NottscriptParser.LogicalTypeContext ctx) {
        List<Dimension> dims = visitAnArraySpec(ctx.arraySpec());
        return new IntrinsicType(ctx.start, VarType.LOGICAL, dims);
    }

    @Override
    public Ast visitDerivedType(NottscriptParser.DerivedTypeContext ctx) {
        String name = ctx.NAME().getText();
        List<Dimension> dims = visitAnArraySpec(ctx.arraySpec());
        return new DerivedType(ctx.start, name, dims);
    }

    // -----------------------------------------------------------------
    // Statements
    // -----------------------------------------------------------------

    @Override
    public Ast visitAssignmentStmt(NottscriptParser.AssignmentStmtContext ctx) {
        Expression lvalue = (Expression) visit(ctx.postfixExpr());
        Expression rvalue = (Expression) visit(ctx.expr());
        return new AssignmentStmt(ctx.start, lvalue, rvalue);
    }

    @Override
    public Ast visitCallStmt(NottscriptParser.CallStmtContext ctx) {
        String name = ctx.NAME().getText();
        List<Expression> args = visitAnExprList(ctx.exprList());
        return new CallStmt(ctx.start, name, args);
    }

    @Override
    public Ast visitIfSimpleStmt(NottscriptParser.IfSimpleStmtContext ctx) {
        Expression condition = (Expression) visit(ctx.expr());
        Statement thenStmt = (Statement) visit(ctx.statement());
        return new IfSimpleStmt(ctx.start, condition, thenStmt);
    }

    @Override
    public Ast visitIfThenElseStmt(NottscriptParser.IfThenElseStmtContext ctx) {
        Expression condition = (Expression) visit(ctx.expr());
        // block(0) is always the 'then' block
        List<Statement> thenBlock = visitAndMap(ctx.statementBlock(0).statement(), Statement.class);
        // block(1) is the 'else' block, if it exists
        List<Statement> elseBlock = (ctx.ELSE() != null && ctx.statementBlock(1) != null) ? visitAndMap(ctx.statementBlock(1).statement(), Statement.class) : Collections.emptyList();
        return new IfThenElseStmt(ctx.start, condition, thenBlock, elseBlock);
    }

    @Override
    public Ast visitDoLoopStmt(NottscriptParser.DoLoopStmtContext ctx) {
        String var = ctx.NAME().getText();
        Expression start = (Expression) visit(ctx.expr(0));
        Expression end = (Expression) visit(ctx.expr(1));
        // Step (expr(2)) is optional
        Expression step = (ctx.expr(2) != null) ? (Expression) visit(ctx.expr(2)) : null;
        List<Statement> body = visitAndMap(ctx.statementBlock().statement(), Statement.class);
        return new DoLoopStmt(ctx.start, var, start, end, step, body);
    }

    @Override
    public Ast visitDoWhileLoopStmt(NottscriptParser.DoWhileLoopStmtContext ctx) {
        Expression condition = (Expression) visit(ctx.expr());
        List<Statement> body = visitAndMap(ctx.statementBlock().statement(), Statement.class);
        return new DoWhileStmt(ctx.start, condition, body);
    }

    @Override
    public Ast visitReadStmt(NottscriptParser.ReadStmtContext ctx) {
        List<Expression> lvalues = visitAndMap(ctx.postfixExpr(), Expression.class);
        return new ReadStmt(ctx.start, lvalues);
    }

    @Override
    public Ast visitWriteStmt(NottscriptParser.WriteStmtContext ctx) {
        List<Expression> exprs = visitAnExprList(ctx.exprList());
        return new WriteStmt(ctx.start, exprs);
    }

    @Override
    public Ast visitAllocateStmt(NottscriptParser.AllocateStmtContext ctx) {
        String name = ctx.NAME().getText();
        List<Expression> dims = visitAnExprList(ctx.exprList()); // Handles null list
        return new AllocateStmt(ctx.start, name, dims);
    }

    @Override
    public Ast visitDeallocateStmt(NottscriptParser.DeallocateStmtContext ctx) {
        String name = ctx.NAME().getText();
        return new DeallocateStmt(ctx.start, name);
    }

    // -----------------------------------------------------------------
    // Expressions
    // -----------------------------------------------------------------

    // --- Binary Operations (Precedence climbing) ---
    // These methods "fold" the left-associative binary expressions.

    @Override
    public Ast visitOrExpr(NottscriptParser.OrExprContext ctx) {
        Expression left = (Expression) visit(ctx.andExpr(0));
        for (int i = 0; i < ctx.OR_OP().size(); i++) {
            Token opToken = ctx.OR_OP(i).getSymbol();
            Expression right = (Expression) visit(ctx.andExpr(i + 1));
            left = new BinaryOpExpr(left.startToken(), left, opToken, right);
        }
        return left;
    }

    @Override
    public Ast visitAndExpr(NottscriptParser.AndExprContext ctx) {
        Expression left = (Expression) visit(ctx.relExpr(0));
        for (int i = 0; i < ctx.AND_OP().size(); i++) {
            Token opToken = ctx.AND_OP(i).getSymbol();
            Expression right = (Expression) visit(ctx.relExpr(i + 1));
            left = new BinaryOpExpr(left.startToken(), left, opToken, right);
        }
        return left;
    }

    @Override
    public Ast visitRelExpr(NottscriptParser.RelExprContext ctx) {
        Expression left = (Expression) visit(ctx.concatExpr(0));
        for (int i = 0; i < ctx.relOp().size(); i++) {
            // The op token is the (only) child of the relOp context
            Token opToken = (Token) ctx.relOp(i).getChild(0).getPayload();
            Expression right = (Expression) visit(ctx.concatExpr(i + 1));
            left = new BinaryOpExpr(left.startToken(), left, opToken, right);
        }
        return left;
    }

    @Override
    public Ast visitConcatExpr(NottscriptParser.ConcatExprContext ctx) {
        Expression left = (Expression) visit(ctx.addExpr(0));
        for (int i = 0; i < ctx.CONCAT().size(); i++) {
            Token opToken = ctx.CONCAT(i).getSymbol();
            Expression right = (Expression) visit(ctx.addExpr(i + 1));
            left = new BinaryOpExpr(left.startToken(), left, opToken, right);
        }
        return left;
    }

    @Override
    public Ast visitAddExpr(NottscriptParser.AddExprContext ctx) {
        Expression left = (Expression) visit(ctx.mulExpr(0));
        // For rules with multiple operators (e.g. + or -), we get the op
        // from the general child list.
        int opCount = ctx.mulExpr().size() - 1;
        for (int i = 0; i < opCount; i++) {
            // Child 1, 3, 5... will be the operator token
            Token opToken = (Token) ctx.getChild(2 * i + 1).getPayload();
            Expression right = (Expression) visit(ctx.mulExpr(i + 1));
            left = new BinaryOpExpr(left.startToken(), left, opToken, right);
        }
        return left;
    }

    @Override
    public Ast visitMulExpr(NottscriptParser.MulExprContext ctx) {
        Expression left = (Expression) visit(ctx.powExpr(0));
        int opCount = ctx.powExpr().size() - 1;
        for (int i = 0; i < opCount; i++) {
            Token opToken = (Token) ctx.getChild(2 * i + 1).getPayload();
            Expression right = (Expression) visit(ctx.powExpr(i + 1));
            left = new BinaryOpExpr(left.startToken(), left, opToken, right);
        }
        return left;
    }

    @Override
    public Ast visitPowExpr(NottscriptParser.PowExprContext ctx) {
        // Power is right-associative
        Expression left = (Expression) visit(ctx.postfixExpr());
        if (ctx.powExpr() != null) {
            Token opToken = ctx.EXP().getSymbol();
            Expression right = (Expression) visit(ctx.powExpr());
            return new BinaryOpExpr(left.startToken(), left, opToken, right);
        }
        return left; // No exponent, just return the base
    }

    // --- Postfix Operations ---

    @Override
    public Ast visitPostfixExpr(NottscriptParser.PostfixExprContext ctx) {
        // Start with the base atom
        Expression base = (Expression) visit(ctx.atom());

        // Sequentially apply all suffixes
        for (NottscriptParser.PostfixSuffixContext suffixCtx : ctx.postfixSuffix()) {
            if (suffixCtx instanceof NottscriptParser.FieldAccessContext) {
                NottscriptParser.FieldAccessContext fac = (NottscriptParser.FieldAccessContext) suffixCtx;
                String fieldName = fac.NAME().getText();
                base = new FieldAccessExpr(base.startToken(), base, fieldName);
            } else if (suffixCtx instanceof NottscriptParser.CallOrIndexContext) {
                NottscriptParser.CallOrIndexContext cic = (NottscriptParser.CallOrIndexContext) suffixCtx;
                List<Expression> args = visitAnExprList(cic.exprList());
                base = new CallOrIndexExpr(base.startToken(), base, args);
            }
        }
        return base;
    }

    // --- Atoms ---

    @Override
    public Ast visitParenExpr(NottscriptParser.ParenExprContext ctx) {
        // Simply return the visited inner expression, "flattening" the parentheses.
        return visit(ctx.expr());
    }

    @Override
    public Ast visitLiteralExpr(NottscriptParser.LiteralExprContext ctx) {
        return visit(ctx.literal()); // Delegate to literal visitor
    }

    @Override
    public Ast visitNameExpr(NottscriptParser.NameExprContext ctx) {
        return new NameExpr(ctx.start, ctx.NAME().getText());
    }

    // --- Literals ---

    @Override
    public Ast visitLiteral(NottscriptParser.LiteralContext ctx) {
        if (ctx.INT_LITERAL() != null) {
            String text = ctx.INT_LITERAL().getText();
            return new IntLiteral(ctx.start, Integer.parseInt(text));
        }
        if (ctx.REAL_LITERAL() != null) {
            String text = ctx.REAL_LITERAL().getText();
            return new RealLiteral(ctx.start, Double.parseDouble(text));
        }
        if (ctx.LOGICAL_LITERAL() != null) {
            boolean val = ctx.LOGICAL_LITERAL().getText().equals(".true.");
            return new LogicalLiteral(ctx.start, val);
        }
        if (ctx.CHAR_LITERAL() != null) {
            // Remove surrounding quotes and unescape doubled quotes ("") to (")
            String text = ctx.CHAR_LITERAL().getText();
            String unquoted = text.substring(1, text.length() - 1);
            String unescaped = unquoted.replace("\"\"", "\"");
            return new CharLiteral(ctx.start, unescaped);
        }
        if (ctx.B_LITERAL() != null) {
            return new BozLiteral(ctx.start, ctx.B_LITERAL().getText(), 'b');
        }
        if (ctx.O_LITERAL() != null) {
            return new BozLiteral(ctx.start, ctx.O_LITERAL().getText(), 'o');
        }
        if (ctx.Z_LITERAL() != null) {
            return new BozLiteral(ctx.start, ctx.Z_LITERAL().getText(), 'z');
        }
        // This should be unreachable if the grammar is correct
        throw new IllegalStateException("Unknown literal type: " + ctx.getText());
    }

    // -----------------------------------------------------------------
    // Helper Methods
    // -----------------------------------------------------------------

    /**
     * Visits a list of parse tree nodes and casts them to the specified AST node type.
     */
    private <T extends Ast> List<T> visitAndMap(List<? extends ParseTree> nodes, Class<T> clazz) {
        return nodes.stream().map(this::visit).map(clazz::cast).collect(Collectors.toList());
    }

    /**
     * Helper to visit a 'nameList' context and return a simple List of Strings.
     */
    private List<String> visitANameList(NottscriptParser.NameListContext ctx) {
        if (ctx == null) {
            return Collections.emptyList();
        }
        return ctx.NAME().stream().map(TerminalNode::getText).collect(Collectors.toList());
    }

    /**
     * Helper to visit an 'exprList' context and return a List of Expressions.
     */
    private List<Expression> visitAnExprList(NottscriptParser.ExprListContext ctx) {
        if (ctx == null) {
            return Collections.emptyList();
        }
        return visitAndMap(ctx.expr(), Expression.class);
    }

    /**
     * Helper to visit an 'arraySpec' context and return a List of Dimensions.
     */
    private List<Dimension> visitAnArraySpec(NottscriptParser.ArraySpecContext ctx) {
        if (ctx == null) {
            return Collections.emptyList();
        }
        // dimList : dim (COMMA dim)*
        // dim : INT_LITERAL | STAR
        return ctx.dimList().dim().stream().map(dimCtx -> {
            if (dimCtx.INT_LITERAL() != null) {
                return new LiteralDim(Integer.parseInt(dimCtx.INT_LITERAL().getText()));
            } else { // Must be STAR
                return new PointerDim();
            }
        }).collect(Collectors.toList());
    }
}